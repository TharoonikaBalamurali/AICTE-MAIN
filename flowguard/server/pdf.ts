/** PDF rendering for deficiency notices and scrutiny / re-scrutiny reports (pdfkit, standard fonts). */
import PDFDocument from 'pdfkit';

interface Block {
  heading: string;
  items: Array<{ title?: string; lines: string[] }>;
}
interface Doc {
  title: string;
  subtitle: string;
  meta: Array<[string, string]>;
  blocks: Block[];
  footer: string;
}

/** Standard PDF fonts use WinAnsi encoding; map characters it cannot show. */
const ascii = (s: unknown) =>
  String(s ?? '—')
    .replace(/[→↔]/g, '->')
    .replace(/[–—]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/…/g, '...')
    .replace(/₹/g, 'Rs.')
    .replace(/≥/g, '>=')
    .replace(/≤/g, '<=')
    // eslint-disable-next-line no-control-regex
    .replace(/[^\x09\x0A\x0D\x20-\x7E\xA0-\xFF]/g, '?');

export function renderPdf(d: Doc): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const pdf = new PDFDocument({ size: 'A4', margin: 50, info: { Title: ascii(d.title), Creator: 'AICTE Approval Portal' } });
    const chunks: Buffer[] = [];
    pdf.on('data', (c: Buffer) => chunks.push(c));
    pdf.on('end', () => resolve(Buffer.concat(chunks)));
    pdf.on('error', reject);
    const W = pdf.page.width - 100;
    pdf.fillColor('#10213f').font('Helvetica-Bold').fontSize(16).text('AICTE Approval Portal');
    pdf.font('Helvetica').fontSize(9).fillColor('#64748b').text('Unified Approval Workflow & Compliance Management Portal');
    pdf.moveDown(0.8);
    pdf.fillColor('#0f172a').font('Helvetica-Bold').fontSize(14).text(ascii(d.title));
    pdf.font('Helvetica').fontSize(10).fillColor('#334155').text(ascii(d.subtitle));
    pdf.moveDown(0.6);
    for (const [k, v] of d.meta) {
      pdf.font('Helvetica-Bold').fontSize(9).fillColor('#475569').text(`${ascii(k)}: `, { continued: true }).font('Helvetica').fillColor('#0f172a').text(ascii(v), { width: W });
    }
    for (const b of d.blocks) {
      pdf.moveDown(0.8);
      pdf.font('Helvetica-Bold').fontSize(11).fillColor('#1748b8').text(ascii(b.heading).toUpperCase());
      pdf.moveTo(50, pdf.y + 2).lineTo(50 + W, pdf.y + 2).strokeColor('#dbe7fe').stroke();
      pdf.moveDown(0.4);
      if (b.items.length === 0) pdf.font('Helvetica').fontSize(9).fillColor('#64748b').text('None.');
      for (const it of b.items) {
        if (it.title) pdf.font('Helvetica-Bold').fontSize(9.5).fillColor('#0f172a').text(ascii(it.title), { width: W });
        for (const l of it.lines) pdf.font('Helvetica').fontSize(9).fillColor('#334155').text(ascii(l), { width: W, indent: it.title ? 10 : 0 });
        pdf.moveDown(0.35);
      }
    }
    pdf.moveDown(1);
    pdf.font('Helvetica-Oblique').fontSize(8).fillColor('#64748b').text(ascii(d.footer), { width: W });
    pdf.end();
  });
}

const fmt = (iso: unknown) => (iso ? new Date(String(iso)).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata', dateStyle: 'medium', timeStyle: 'short' }) + ' IST' : '—');

export function noticePdf(n: any): Promise<Buffer> {
  return renderPdf({
    title: `Deficiency Notice ${n.noticeNo} (version ${n.version})`,
    subtitle: n.kind === 'FURTHER_CORRECTION' ? 'Further correction required after re-scrutiny' : 'Deficiencies observed during scrutiny',
    meta: [
      ['Application ID', n.application.referenceNo],
      ['Submission version', String(n.application.submissionVersion)],
      ['Application type', `${n.application.categoryTitle}${n.application.subtypeLabel ? ` - ${n.application.subtypeLabel}` : ''}`],
      ['Institution', `${n.institution.name} (${n.institution.aicteInstitutionId}, ID ${String(n.institution.idVerification).toLowerCase()})`],
      ['Issue date', fmt(n.issuedAt)],
      ['Issuing officer', `${n.issuedBy.name} (${n.issuedBy.role})`],
      ...(n.supersedes ? ([['Supersedes', n.supersedes]] as Array<[string, string]>) : []),
    ],
    blocks: [
      {
        heading: 'Summary of scrutiny results',
        items: [{ lines: [n.scrutinySummary] }],
      },
      {
        heading: 'Deficiencies and required corrections',
        items: n.deficiencies.map((d: any, i: number) => ({
          title: `${i + 1}. ${d.referenceNo} - ${d.target.label}`,
          lines: [
            `Category: ${String(d.category).replace(/_/g, ' ').toLowerCase()}`,
            `Deficiency: ${d.explanation}`,
            `Required correction: ${d.correctiveAction}`,
            ...(d.requiredReplacement ? [`Replacement document / information required: ${d.requiredReplacement}`] : []),
            `Source reference: ${d.sourceReference ?? 'Not specified'}`,
            `Deadline: ${d.deadline.label}`,
          ],
        })),
      },
      { heading: 'Next steps for the institution', items: [{ lines: n.nextSteps.map((s: string, i: number) => `${i + 1}. ${s}`) }] },
    ],
    footer: `${n.disclaimer} Notice generated by the AICTE Approval Portal; it is not an official AICTE portal communication.`,
  });
}

export function reportPdf(r: any): Promise<Buffer> {
  const base: Array<[string, string]> = [
    ['Application ID', r.application.referenceNo],
    ['Submission version', String(r.application.submissionVersion)],
    ['Application type', r.application.categoryTitle],
    ['Institution', `${r.institution.name} (${r.institution.aicteInstitutionId})`],
    ['Report version', String(r.version)],
    ['Generated', fmt(r.generatedAt)],
    ['Rules evaluated', `${r.run.rulesEvaluated} on ${String(r.run.evaluationDate).slice(0, 10)} (input hash ${String(r.run.inputHash).slice(0, 12)})`],
  ];
  const fline = (f: any) => `[${f.status}] ${f.targetLabel}: ${f.explanation}${f.sourceReference ? ` (${f.sourceReference})` : ''} - rule ${f.ruleId} v${f.ruleVersion}`;
  if (r.kind === 'RE_SCRUTINY') {
    return renderPdf({
      title: `Re-scrutiny report v${r.version}`,
      subtitle: r.scopeNote,
      meta: base,
      blocks: [
        {
          heading: 'Deficiency-by-deficiency review',
          items: r.deficiencies.map((d: any) => ({
            title: `${d.referenceNo} - ${d.target.label} - automated assessment: ${d.automatedAssessment}`,
            lines: [
              `Original finding: ${d.original.explanation}`,
              `Required correction: ${d.original.correctiveAction}`,
              `Correction submitted: ${d.correction.response ?? '—'}`,
              ...(d.correction.documents ?? []).map((x: any) => `Document: v${x.before?.version ?? '-'} -> v${x.after.version} (${x.after.fileName})`),
              ...Object.keys(d.correction.fieldChanges?.after ?? {}).map((k) => `Field ${k}: "${d.correction.fieldChanges.before?.[k] ?? '—'}" -> "${d.correction.fieldChanges.after[k]}"`),
              ...d.newResults.map(fline),
              `Human verification required: ${d.humanVerificationRequired ? 'Yes' : 'No'}`,
              `Source: ${d.sourceReference ?? '—'}`,
            ],
          })),
        },
        { heading: 'Dependent checks re-evaluated', items: [{ lines: r.dependentChecks.map(fline) }] },
      ],
      footer: r.disclaimer,
    });
  }
  return renderPdf({
    title: `Scrutiny report v${r.version}`,
    subtitle: `Overall: ${r.summary.discrepanciesDetected ? 'discrepancies detected' : 'no discrepancies detected'}; ${r.summary.verificationRequired ? 'human verification required' : 'no additional verification flagged'}; ready for officer review.`,
    meta: base,
    blocks: [
      { heading: 'Outstanding findings', items: [{ lines: r.summary.outstanding.map((f: any) => `[${f.status}] ${f.targetLabel}: ${f.explanation}`) }] },
      { heading: 'Missing documents', items: [{ lines: r.documents.missing }] },
      {
        heading: 'Documents',
        items: r.documents.expected.map((d: any) => ({
          title: `${d.name} [${d.requirement}] - ${d.status}`,
          lines: [d.submitted ? `Submitted: ${d.submitted.fileName} v${d.submitted.version}` : 'Not submitted', ...d.findings.filter((f: any) => f.status !== 'PASS').map(fline)],
        })),
      },
      { heading: 'Fields', items: r.fields.map((f: any) => ({ title: `${f.label} - ${f.status}`, lines: [String(f.value), ...f.findings.filter((x: any) => x.status !== 'PASS').map(fline)] })) },
      { heading: 'Validity and expiry', items: [{ lines: r.validity.map(fline) }] },
      { heading: 'Signatures and signatories', items: [{ lines: r.signatures.map(fline) }] },
      { heading: 'Other discrepancies', items: [{ lines: r.otherDiscrepancies.map(fline) }] },
      { heading: 'Items requiring human verification', items: [{ lines: r.humanVerification.map(fline) }] },
    ],
    footer: r.disclaimer,
  });
}
