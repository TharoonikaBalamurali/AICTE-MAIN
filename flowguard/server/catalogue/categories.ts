const base: FieldDef[] = [fAcademicYear, fSignatoryName, fSignatoryDesignation];

function f(id: string, label: string, type: FieldDef['type'], group: string, extra: Partial<FieldDef> = {}): FieldDef {
  return { id, label, type, group, required: true, classification: 'SYSTEM_METADATA', ...extra };
}
const sel = (pairs: Array<[string, string]>) => pairs.map(([value, label]) => ({ value, label }));

const S_ONLY = (aphReference: string, period: ProcessingRoute['processingPeriod']): ProcessingRoute => ({
  scrutiny: true,
  evc: 'NO',
  shc: 'NO',
  processingPeriod: period,
  aphReference,
});
const S_EVC = (aphReference: string, period: ProcessingRoute['processingPeriod'], shc: ProcessingRoute['shc'] = 'AS_APPLICABLE'): ProcessingRoute => ({
  scrutiny: true,
  evc: 'YES',
  shc,
  processingPeriod: period,
  aphReference,
});
const SELF = (aphReference: string): ProcessingRoute => ({
  scrutiny: false,
  evc: 'NO',
  shc: 'NO',
  processingPeriod: 'PUBLIC_NOTICE',
  aphReference,
  notes: 'Table 2.3 lists Self-Disclosure only. Institutions may be selected at random for EVC (Ch. II §2.3.5) — not modelled as a default step.',
});

